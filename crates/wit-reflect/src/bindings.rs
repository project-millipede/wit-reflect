//! Rendering of the bindings file.
//!
//! The bindings file holds the part of a component's `wit_bindgen::generate!`
//! call that follows from the schema: the world, the derive that lets
//! forwarding assemble binding values, and one `with` entry per type that
//! crosses unchanged. The component crate adds only what describes its own
//! layout, such as the WIT directory.
//!
//! A `with` entry makes the bindings use the owner type itself instead of
//! defining a type of their own. wit-bindgen rejects an entry for a type its
//! world does not contain, so entries are limited to the interfaces the world
//! reaches.

use std::collections::BTreeSet;

use crate::forwarding::ForwardingErrors;
use crate::identifier::Escaped;
use crate::resolve::{ResolvedPackage, World};

const INDENT: &str = "    ";

impl ResolvedPackage {
    /// Render the Rust source that sets up the bindings of `world`.
    ///
    /// The file defines the macro `generate_bindings!`. It expands to
    /// `wit_bindgen::generate!` with everything the schema determines:
    ///
    /// - the world;
    /// - [`FromParts`](crate::lower::FromParts) on the generated types, so
    ///   forwarding can assemble them;
    /// - a `with` entry for every type that crosses unchanged, which makes the
    ///   bindings use the owner type itself.
    ///
    /// The component crate includes the file and passes the remaining options:
    ///
    /// ```text
    /// include!("bindings.rs");
    /// generate_bindings! { path: "wit" }
    /// ```
    ///
    /// A type crosses unchanged when its derive found nothing that changes
    /// its shape, it is `Clone` and `Debug`, and every type inside it crosses
    /// unchanged too. Its entry names it at its owner crate's root unless the
    /// type declares `#[wit(path = …)]`; a path that does not resolve is a
    /// compile error in the component crate. `#[wit(convert)]` on a type
    /// keeps it converted.
    ///
    /// The file follows wit-bindgen 0.63.
    ///
    /// # Errors
    ///
    /// Returns [`ForwardingError::UnknownWorld`](crate::ForwardingError::UnknownWorld)
    /// if the schema declares no world of that name.
    pub fn bindings(&self, world: &str) -> Result<String, ForwardingErrors> {
        let Some(declared_world) = self.world(world) else {
            return Err(ForwardingErrors::unknown_world(world));
        };

        let mut mappings = Vec::new();
        for position in self.reached_interfaces(declared_world) {
            let interface = &self.interfaces[position];
            let interface_id = self.name.item_id(&interface.name);
            for definition in &interface.definitions {
                if let Some(owner_path) = definition.owner_path {
                    let type_name = &definition.name;
                    mappings.push(format!("\"{interface_id}/{type_name}\": {owner_path},"));
                }
            }
        }

        let mut lines = vec![
            format!(
                "// Generated by wit-reflect from the schema of `{}`, world `{world}`.",
                self.name
            ),
            "// Do not edit. Change the Rust declarations or the schema and regenerate.".to_owned(),
            "//".to_owned(),
            "// `generate_bindings!` is `wit_bindgen::generate!` with everything the schema"
                .to_owned(),
            "// determines filled in. Pass it the remaining options, such as `path`.".to_owned(),
        ];
        if !mappings.is_empty() {
            lines.extend(
                [
                    "//",
                    "// Each `with` entry names an owner type that crosses the boundary unchanged:",
                    "// the bindings use that type instead of defining their own. Its path is the",
                    "// owner crate's root unless the type declares `#[wit(path = …)]`. To have a",
                    "// type converted instead, mark it `#[wit(convert)]`.",
                ]
                .map(str::to_owned),
            );
        }
        lines.push(String::new());
        lines.push("macro_rules! generate_bindings {".to_owned());
        lines.push(format!("{INDENT}($($options:tt)*) => {{"));
        let call_depth = INDENT.repeat(2);
        let option_depth = INDENT.repeat(3);
        lines.push(format!("{call_depth}::wit_bindgen::generate!({{"));
        lines.push(format!(
            "{option_depth}world: \"{}\",",
            self.name.item_id(world)
        ));
        lines.push(format!(
            "{option_depth}additional_derives: [::wit_reflect::FromParts],"
        ));
        if !mappings.is_empty() {
            lines.push(format!("{option_depth}with: {{"));
            let mapping_depth = INDENT.repeat(4);
            for mapping in mappings {
                lines.push(format!("{mapping_depth}{mapping}"));
            }
            lines.push(format!("{option_depth}}},"));
        }
        // The caller's options come last, so they may end with or without a comma.
        lines.push(format!("{option_depth}$($options)*"));
        lines.push(format!("{call_depth}}});"));
        lines.push(format!("{INDENT}}};"));
        lines.push("}".to_owned());

        let mut text = lines.join("\n");
        text.push('\n');
        Ok(text)
    }

    /// The positions of this package's interfaces that `world` contains: those
    /// it imports or exports, and those they `use` types from, in declaration
    /// order.
    fn reached_interfaces(&self, world: &World) -> BTreeSet<usize> {
        let mut pending: Vec<usize> = world
            .items
            .iter()
            .filter_map(|item| item.interface)
            .collect();
        let mut reached = BTreeSet::new();
        while let Some(position) = pending.pop() {
            if !reached.insert(position) {
                continue;
            }
            for used in &self.interfaces[position].uses {
                // A `use` of this package names the interface alone; an
                // external one is a path and matches no interface here.
                let used_position = self
                    .interfaces
                    .iter()
                    .position(|interface| Escaped(&interface.name).to_string() == used.source);
                pending.extend(used_position);
            }
        }
        reached
    }
}
